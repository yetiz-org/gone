func _ParseValue(raw string) any {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return ""
	}

	var v any
	if err := json.Unmarshal([]byte(raw), &v); err == nil {
		return v
	}

	if f, err := strconv.ParseFloat(raw, 64); err == nil {
		return f
	}

	return raw
}

func _DecodeStructured(raw string, dst any) bool {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return false
	}

	if err := yaml.Unmarshal([]byte(raw), dst); err == nil {
		return true
	}

	return json.Unmarshal([]byte(raw), dst) == nil
}

func _BuildTagsFromGOFLAGS() []string {
	fields := _SplitDirectiveFields(os.Getenv("GOFLAGS"))
	out := []string{}
	for i := 0; i < len(fields); i++ {
		field := fields[i]
		if field == "-tags" && i+1 < len(fields) {
			out = append(out, _SplitBuildTags(fields[i+1])...)
			i++

			continue
		}

		if tags, ok := strings.CutPrefix(field, "-tags="); ok {
			out = append(out, _SplitBuildTags(tags)...)
		}
	}

	return out
}

func _SplitBuildTags(raw string) []string {
	raw = strings.ReplaceAll(raw, ",", " ")
	fields := strings.Fields(raw)
	out := make([]string, 0, len(fields))
	for _, field := range fields {
		field = strings.TrimSpace(field)
		if field != "" {
			out = append(out, field)
		}
	}

	return out
}

func _MergeBuildTags(groups ...[]string) []string {
	seen := map[string]bool{}
	out := []string{}
	for _, group := range groups {
		for _, tag := range group {
			tag = strings.TrimSpace(tag)
			if tag == "" || seen[tag] {
				continue
			}

			seen[tag] = true
			out = append(out, tag)
		}
	}

	return out
}

func _Contains(fields []string, value string) bool {
	for _, f := range fields {
		if f == value {
			return true
		}
	}

	return false
}

func _TakeFirstField(s string) (string, string) {
	fields := _SplitDirectiveFields(s)
	if len(fields) == 0 {
		return "", ""
	}

	first := fields[0]
	idx := strings.Index(s, first)
	if idx < 0 {
		return first, ""
	}

	return first, strings.TrimSpace(s[idx+len(first):])
}

func _SplitDirectiveFields(s string) []string {
	var fields []string
	var b strings.Builder
	quote := rune(0)
	escaped := false
	jsonDepth := 0
	jsonString := false
	jsonEscaped := false

	for _, r := range s {
		if jsonDepth > 0 {
			b.WriteRune(r)
			if jsonEscaped {
				jsonEscaped = false

				continue
			}

			if jsonString {
				switch r {
				case '\\':
					jsonEscaped = true
				case '"':
					jsonString = false
				}

				continue
			}

			switch r {
			case '"':
				jsonString = true
			case '{', '[':
				jsonDepth++
			case '}', ']':
				jsonDepth--
			}

			continue
		}

		if escaped {
			b.WriteRune(r)
			escaped = false

			continue
		}

		if quote != 0 {
			if r == '\\' {
				escaped = true

				continue
			}

			if r == quote {
				quote = 0

				continue
			}

			b.WriteRune(r)

			continue
		}

		switch r {
		case '\'', '"':
			if b.Len() == 0 {
				quote = r
			} else {
				b.WriteRune(r)
			}
		case '{', '[':
			jsonDepth = 1
			b.WriteRune(r)
		case ' ', '\t', '\n', '\r':
			if b.Len() > 0 {
				fields = append(fields, b.String())
				b.Reset()
			}
		default:
			b.WriteRune(r)
		}
	}

	if b.Len() > 0 {
		fields = append(fields, b.String())
	}

	return fields
}
