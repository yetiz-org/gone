func _NewASTSchemaBuilderWithState(
	files []*ast.File,
	pkgPath string,
	rootPkgPath string,
	dir string,
	buildTags []string,
	imports map[string]string,
	selfAliases map[string]bool,
	components map[string]*Schema,
	componentPkgs map[string]string,
	componentOwners map[string]string,
	visiting map[string]bool,
	importBuilders map[string]*_ASTSchemaBuilder,
	importNames *sync.Map,
) *_ASTSchemaBuilder {
	if importNames == nil {
		importNames = &sync.Map{}
	}

	b := &_ASTSchemaBuilder{
		_PkgPath:         pkgPath,
		_RootPkgPath:     rootPkgPath,
		_Dir:             dir,
		_BuildTags:       append([]string(nil), buildTags...),
		_Imports:         _CloneStringMap(imports),
		_ImportNames:     importNames,
		_SelfAliases:     _CloneBoolMap(selfAliases),
		_ImportBuilders:  importBuilders,
		_TypeSpecs:       map[string]*ast.TypeSpec{},
		_TypeSpecImports: map[*ast.TypeSpec]map[string]string{},
		_TypeSpecNames:   map[*ast.TypeSpec]string{},
		_Components:      components,
		_ComponentPkgs:   componentPkgs,
		_ComponentOwners: componentOwners,
		_Visiting:        visiting,
	}

	if pkgPath != "" {
		if _, exists := importBuilders[pkgPath]; !exists {
			importBuilders[pkgPath] = b
		}
	}

	for _, file := range files {
		if b._PackageName == "" && file.Name != nil {
			b._PackageName = file.Name.Name
		}

		fileImports := _ASTImports(file, b._Dir, b._BuildTags, b._ImportNames)

		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}

			for _, spec := range gen.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok || typeSpec.Name == nil {
					continue
				}

				b._TypeSpecs[typeSpec.Name.Name] = typeSpec
				b._TypeSpecImports[typeSpec] = fileImports
				b._TypeSpecNames[typeSpec] = _ASTSchemaName(gen, typeSpec)
			}
		}
	}

	return b
}

func _ASTSchemaName(gen *ast.GenDecl, typeSpec *ast.TypeSpec) string {
	text := ""
	if typeSpec != nil && typeSpec.Doc != nil {
		text = typeSpec.Doc.Text()
	} else if gen != nil && gen.Doc != nil {
		text = gen.Doc.Text()
	}

	for _, line := range strings.Split(strings.TrimRight(text, "\n"), "\n") {
		name, payload, ok := _Directive(line)
		if !ok {
			continue
		}

		switch name {
		case "schemaName", "componentName":
			return _SanitizeComponentName(strings.TrimSpace(payload))
		}
	}

	return ""
}

func _ASTImportsFromPrimary(files []*ast.File, primary *ast.File, dir string, buildTags []string, importNames *sync.Map) map[string]string {
	out := map[string]string{}
	conflicts := map[string]bool{}
	for _, file := range files {
		for alias, importPath := range _ASTImports(file, dir, buildTags, importNames) {
			if existing, exists := out[alias]; exists && existing != importPath {
				delete(out, alias)
				conflicts[alias] = true

				continue
			}

			if !conflicts[alias] {
				out[alias] = importPath
			}
		}
	}

	if primary != nil {
		for alias, importPath := range _ASTImports(primary, dir, buildTags, importNames) {
			out[alias] = importPath
		}
	}

	return out
}

func _ASTImports(file *ast.File, dir string, buildTags []string, importNames *sync.Map) map[string]string {
	out := map[string]string{}
	if file == nil {
		return out
	}

	for _, spec := range file.Imports {
		alias, importPath, ok := _ASTImportBinding(spec, dir, buildTags, importNames)
		if ok {
			out[alias] = importPath
		}
	}

	return out
}

func _CloneStringMap(in map[string]string) map[string]string {
	out := map[string]string{}
	for key, value := range in {
		out[key] = value
	}

	return out
}

func _CloneBoolMap(in map[string]bool) map[string]bool {
	out := map[string]bool{}
	for key, value := range in {
		out[key] = value
	}

	return out
}

func _ASTImportBinding(spec *ast.ImportSpec, dir string, buildTags []string, importNames *sync.Map) (string, string, bool) {
	if spec == nil || spec.Path == nil {
		return "", "", false
	}

	importPath, err := strconv.Unquote(spec.Path.Value)
	if err != nil || importPath == "" {
		return "", "", false
	}

	if spec.Name != nil {
		switch spec.Name.Name {
		case ".", "_":
			return "", "", false
		case "":
			return _ImportPackageName(importPath, dir, buildTags, importNames), importPath, true
		default:
			return spec.Name.Name, importPath, true
		}
	}

	return _ImportPackageName(importPath, dir, buildTags, importNames), importPath, true
}

func (b *_ASTSchemaBuilder) _SchemaForTypeName(raw string) (*Schema, bool) {
	raw = strings.TrimSpace(raw)
	if raw == "" {
		return nil, false
	}

	if strings.HasPrefix(raw, "[]") {
		item, ok := b._SchemaForTypeName(strings.TrimSpace(raw[2:]))
		if !ok {
			return nil, false
		}

		return &Schema{Type: "array", Items: item}, true
	}

	if itemType, ok := strings.CutPrefix(raw, "array:"); ok {
		item, ok := b._SchemaForTypeName(strings.TrimSpace(itemType))
		if !ok {
			return nil, false
		}

		return &Schema{Type: "array", Items: item}, true
	}

	if strings.HasPrefix(raw, "*") {
		inner, ok := b._SchemaForTypeName(strings.TrimSpace(raw[1:]))
		if !ok {
			return nil, false
		}

		return _NullableSchema(inner), true
	}

	expr, err := parser.ParseExpr(raw)
	if err == nil {
		return b._SchemaFromTopLevelExpr(expr, b._Imports)
	}

	typeSpec := b._TypeSpecs[raw]
	if typeSpec == nil {
		return nil, false
	}

	return b._SchemaFromTypeSpec(raw, typeSpec), true
}

func (b *_ASTSchemaBuilder) _SchemaFromTopLevelExpr(expr ast.Expr, imports map[string]string) (*Schema, bool) {
	switch t := expr.(type) {
	case *ast.Ident:
		typeSpec := b._TypeSpecs[t.Name]
		if typeSpec == nil {
			return nil, false
		}

		return b._SchemaFromTypeSpec(t.Name, typeSpec), true
	case *ast.SelectorExpr:
		return b._SchemaFromSelectorExpr(t, imports)
	case *ast.StarExpr:
		inner, ok := b._SchemaFromTopLevelExpr(t.X, imports)
		if !ok {
			return nil, false
		}

		return _NullableSchema(inner), true
	case *ast.ArrayType:
		item, ok := b._SchemaFromTopLevelExpr(t.Elt, imports)
		if !ok {
			return nil, false
		}

		return &Schema{Type: "array", Items: item}, true
	case *ast.IndexExpr:
		return b._SchemaFromGenericExpr(t.X, _SchemaArgs([]ast.Expr{t.Index}, imports), imports)
	case *ast.IndexListExpr:
		return b._SchemaFromGenericExpr(t.X, _SchemaArgs(t.Indices, imports), imports)
	default:
		return nil, false
	}
}

func (b *_ASTSchemaBuilder) _SchemaFromGenericExpr(base ast.Expr, args []_ASTSchemaArg, imports map[string]string) (*Schema, bool) {
	typeName, builder, ok := b._SchemaTypeForExpr(base, imports)
	if !ok {
		return nil, false
	}

	typeSpec := builder._TypeSpecs[typeName]
	if typeSpec == nil {
		return nil, false
	}

	return builder._SchemaFromTypeSpecWithArgs(typeName, typeSpec, args, imports), true
}

func (b *_ASTSchemaBuilder) _SchemaTypeForExpr(expr ast.Expr, imports map[string]string) (string, *_ASTSchemaBuilder, bool) {
	switch t := expr.(type) {
	case *ast.Ident:
		if b._TypeSpecs[t.Name] == nil {
			return "", nil, false
		}

		return t.Name, b, true
	case *ast.SelectorExpr:
		return b._SchemaTypeForSelector(t, imports)
	default:
		return "", nil, false
	}
}

func (b *_ASTSchemaBuilder) _SchemaTypeForSelector(expr *ast.SelectorExpr, imports map[string]string) (string, *_ASTSchemaBuilder, bool) {
	if expr == nil || expr.Sel == nil {
		return "", nil, false
	}

	pkg, ok := expr.X.(*ast.Ident)
	if !ok {
		return "", nil, false
	}

	if _, hasImport := imports[pkg.Name]; hasImport {
		imported, ok := b._ImportedBuilderForAlias(pkg.Name, imports)
		if !ok || imported._TypeSpecs[expr.Sel.Name] == nil {
			return "", nil, false
		}

		return expr.Sel.Name, imported, true
	}

	if b._SelectorNamesCurrentPackage(pkg.Name) {
		if b._TypeSpecs[expr.Sel.Name] != nil {
			return expr.Sel.Name, b, true
		}
	}

	return "", nil, false
}

func (b *_ASTSchemaBuilder) _SchemaFromSelectorExpr(expr *ast.SelectorExpr, imports map[string]string) (*Schema, bool) {
	if pkg, ok := expr.X.(*ast.Ident); ok && pkg.Name == "time" && expr.Sel.Name == "Time" && imports[pkg.Name] == "time" {
		return &Schema{Type: "string", Format: "date-time"}, true
	}

	typeName, builder, ok := b._SchemaTypeForSelector(expr, imports)
	if !ok {
		return nil, false
	}

	return builder._SchemaFromTypeSpec(typeName, builder._TypeSpecs[typeName]), true
}

func (b *_ASTSchemaBuilder) _SelectorNamesCurrentPackage(name string) bool {
	if name == "" {
		return false
	}

	return b._SelfAliases[name]
}

func (b *_ASTSchemaBuilder) _SchemaFromTypeSpec(typeName string, typeSpec *ast.TypeSpec) *Schema {
	return b._SchemaFromTypeSpecWithEnv(typeName, typeSpec, nil)
}

func (b *_ASTSchemaBuilder) _SchemaFromTypeSpecWithArgs(typeName string, typeSpec *ast.TypeSpec, args []_ASTSchemaArg, imports map[string]string) *Schema {
	env := b._TypeParamEnv(typeSpec, args, imports)
	componentTypeName := typeName
	if len(args) > 0 {
		componentTypeName += "." + _SchemaExprComponentSuffix(args, imports)
	}

	return b._SchemaFromTypeSpecWithEnv(componentTypeName, typeSpec, env)
}

func (b *_ASTSchemaBuilder) _SchemaFromTypeSpecWithEnv(typeName string, typeSpec *ast.TypeSpec, env map[string]_ASTSchemaArg) *Schema {
	if _, ok := typeSpec.Type.(*ast.StructType); !ok {
		return b._SchemaFromExpr(typeSpec.Type, env, b._TypeSpecImports[typeSpec])
	}

	componentName := b._ComponentName(typeName, typeSpec)
	if componentName == "" {
		return b._SchemaFromExpr(typeSpec.Type, env, b._TypeSpecImports[typeSpec])
	}
	componentName = b._DisambiguatedComponentName(componentName, typeName)

	if _, exists := b._Components[componentName]; exists {
		return &Schema{Ref: "#/components/schemas/" + componentName}
	}

	if b._Visiting[componentName] {
		return &Schema{Ref: "#/components/schemas/" + componentName}
	}

	b._Visiting[componentName] = true
	b._Components[componentName] = &Schema{Type: "object"}
	b._ComponentPkgs[componentName] = b._PkgPath
	b._Components[componentName] = b._SchemaFromExpr(typeSpec.Type, env, b._TypeSpecImports[typeSpec])
	delete(b._Visiting, componentName)

	return &Schema{Ref: "#/components/schemas/" + componentName}
}

func (b *_ASTSchemaBuilder) _SchemaFromExpr(expr ast.Expr, env map[string]_ASTSchemaArg, imports map[string]string) *Schema {
	switch t := expr.(type) {
	case *ast.Ident:
		if env != nil {
			if mapped, ok := env[t.Name]; ok && mapped._Expr != nil {
				if mappedIdent, ok := mapped._Expr.(*ast.Ident); ok && mappedIdent.Name == t.Name {
					return &Schema{}
				}

				return b._SchemaFromExpr(mapped._Expr, env, mapped._Imports)
			}
		}

		if schema := _SchemaFromIdent(t.Name); schema != nil {
			return schema
		}

		if typeSpec := b._TypeSpecs[t.Name]; typeSpec != nil {
			return b._SchemaFromTypeSpec(t.Name, typeSpec)
		}

		return &Schema{}
	case *ast.StarExpr:
		return _NullableSchema(b._SchemaFromExpr(t.X, env, imports))
	case *ast.ArrayType:
		if _IsByteExpr(t.Elt) {
			return &Schema{Type: "string", Format: "byte"}
		}

		return &Schema{Type: "array", Items: b._SchemaFromExpr(t.Elt, env, imports)}
	case *ast.MapType:
		return &Schema{Type: "object", AdditionalProperties: b._SchemaFromExpr(t.Value, env, imports)}
	case *ast.StructType:
		return b._StructSchema(t, env, imports)
	case *ast.InterfaceType:
		return &Schema{}
	case *ast.SelectorExpr:
		if schema, ok := b._SchemaFromSelectorExpr(t, imports); ok {
			return schema
		}

		return &Schema{}
	case *ast.IndexExpr:
		args := _ResolveSchemaArgs([]ast.Expr{t.Index}, env, imports)
		if schema, ok := b._SchemaFromGenericExpr(t.X, args, imports); ok {
			return schema
		}

		return b._SchemaFromExpr(t.X, env, imports)
	case *ast.IndexListExpr:
		args := _ResolveSchemaArgs(t.Indices, env, imports)
		if schema, ok := b._SchemaFromGenericExpr(t.X, args, imports); ok {
			return schema
		}

		return b._SchemaFromExpr(t.X, env, imports)
	default:
		return &Schema{}
	}
}

func (b *_ASTSchemaBuilder) _StructSchema(st *ast.StructType, env map[string]_ASTSchemaArg, imports map[string]string) *Schema {
	props := map[string]*Schema{}
	required := []string{}

	for _, field := range st.Fields.List {
		if len(field.Names) == 0 {
			embedded := b._EmbeddedStructSchema(field.Type, env, imports)
			if embedded != nil {
				for name, schema := range embedded.Properties {
					props[name] = schema
				}

				required = append(required, embedded.Required...)
			}

			continue
		}

		jsonTag, goaiTag := _ASTStructTags(field)
		if jsonTag == "-" {
			continue
		}

		_, omitempty := splitJSONTag(jsonTag, "")
		for _, name := range field.Names {
			if name == nil || !name.IsExported() {
				continue
			}

			propName, fieldOmitempty := splitJSONTag(jsonTag, name.Name)
			fieldSchema := b._SchemaFromExpr(field.Type, env, imports)
			if goaiTag != "" {
				applyGoaiTag(fieldSchema, goaiTag)
			}

			props[propName] = fieldSchema
			if !omitempty && !fieldOmitempty && !_ASTFieldIsPointer(field.Type) {
				required = append(required, propName)
			}
		}
	}

	return &Schema{Type: "object", Properties: props, Required: required}
}

func (b *_ASTSchemaBuilder) _EmbeddedStructSchema(expr ast.Expr, env map[string]_ASTSchemaArg, imports map[string]string) *Schema {
	switch t := expr.(type) {
	case *ast.StructType:
		return b._StructSchema(t, env, imports)
	case *ast.Ident:
		typeSpec := b._TypeSpecs[t.Name]
		if typeSpec == nil {
			return nil
		}

		st, ok := typeSpec.Type.(*ast.StructType)
		if !ok {
			return nil
		}

		return b._StructSchema(st, env, b._TypeSpecImports[typeSpec])
	default:
		return nil
	}
}

func (b *_ASTSchemaBuilder) _ImportedBuilderForAlias(alias string, imports map[string]string) (*_ASTSchemaBuilder, bool) {
	if alias == "" {
		return nil, false
	}

	importPath := imports[alias]
	if importPath == "" {
		return nil, false
	}

	if imported, ok := b._ImportBuilders[importPath]; ok {
		if imported != nil {
			imported._Imports[alias] = importPath
			imported._SelfAliases[alias] = true
		}

		return imported, imported != nil
	}

	files, dir, ok := b._ImportedPackageFiles(importPath)
	if !ok {
		b._ImportBuilders[importPath] = nil

		return nil, false
	}

	imported := _NewASTSchemaBuilderWithState(
		files,
		importPath,
		b._RootPkgPath,
		dir,
		b._BuildTags,
		nil,
		map[string]bool{alias: true},
		b._Components,
		b._ComponentPkgs,
		b._ComponentOwners,
		b._Visiting,
		b._ImportBuilders,
		b._ImportNames,
	)
	b._ImportBuilders[importPath] = imported
	imported._Imports[alias] = importPath

	return imported, true
}

func (b *_ASTSchemaBuilder) _ImportedPackageFiles(importPath string) ([]*ast.File, string, bool) {
	dir := b._ImportDir(importPath)
	if dir == "" {
		return nil, "", false
	}

	buildCtx := build.Default
	buildCtx.BuildTags = append(append([]string(nil), buildCtx.BuildTags...), b._BuildTags...)
	filter := func(info fs.FileInfo) bool {
		if strings.HasSuffix(info.Name(), "_test.go") {
			return false
		}

		match, err := buildCtx.MatchFile(dir, info.Name())

		return err == nil && match
	}

	pkgs, err := parser.ParseDir(token.NewFileSet(), dir, filter, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return nil, "", false
	}

	files := _ASTPackageFiles(pkgs)
	if len(files) == 0 {
		return nil, "", false
	}

	return files, dir, true
}

func (b *_ASTSchemaBuilder) _ImportDir(importPath string) string {
	if importDir := _ModuleImportDir(b._Dir, importPath); importDir != "" {
		return importDir
	}

	buildCtx := build.Default
	buildCtx.BuildTags = append(append([]string(nil), buildCtx.BuildTags...), b._BuildTags...)
	if _LooksLikeStandardImport(importPath) {
		if pkg, err := buildCtx.Import(importPath, b._Dir, build.FindOnly); err == nil && pkg.Dir != "" {
			return pkg.Dir
		}

		return ""
	}

	return _GoListImportDir(b._Dir, importPath, b._BuildTags)
}

func _ImportPackageName(importPath string, dir string, buildTags []string, importNames *sync.Map) string {
	if importNames == nil {
		importNames = &sync.Map{}
	}

	importDir := _ModuleImportDir(dir, importPath)
	if importDir == "" && _LooksLikeStandardImport(importPath) {
		buildCtx := build.Default
		buildCtx.BuildTags = append(append([]string(nil), buildCtx.BuildTags...), buildTags...)
		if pkg, err := buildCtx.Import(importPath, dir, build.FindOnly); err == nil && pkg.Dir != "" {
			importDir = pkg.Dir
		}
	}

	cacheKey := importDir + "\x00" + strings.Join(buildTags, "\x00")
	if importDir != "" {
		if cached, ok := importNames.Load(cacheKey); ok {
			if name, ok := cached.(string); ok && name != "" {
				return name
			}
		}

		if name, ok := _ParseImportPackageNameFromDir(importDir, buildTags); ok {
			importNames.Store(cacheKey, name)

			return name
		}
	}

	return _DefaultPackageNameFromImportPath(importPath)
}

func _ParseImportPackageNameFromDir(importDir string, buildTags []string) (string, bool) {
	entries, err := os.ReadDir(importDir)
	if err != nil {
		return "", false
	}

	buildCtx := build.Default
	buildCtx.BuildTags = append(append([]string(nil), buildCtx.BuildTags...), buildTags...)
	for _, entry := range entries {
		info, err := entry.Info()
		if err != nil || info.IsDir() || strings.HasSuffix(info.Name(), "_test.go") {
			continue
		}

		match, err := buildCtx.MatchFile(importDir, info.Name())
		if err != nil || !match {
			continue
		}

		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(importDir, info.Name()), nil, parser.PackageClauseOnly)
		if err != nil || file == nil || file.Name == nil || file.Name.Name == "" {
			continue
		}

		return file.Name.Name, true
	}

	return "", false
}

func _DefaultPackageNameFromImportPath(importPath string) string {
	base := importpath.Base(importPath)
	if base == "" || base == "." || base == "/" {
		return ""
	}

	if strings.HasPrefix(base, "v") && len(base) > 1 && _AllDigits(base[1:]) {
		parent := importpath.Base(importpath.Dir(importPath))
		if parent != "" && parent != "." && parent != "/" {
			base = parent
		}
	}

	if idx := strings.LastIndex(base, "."); idx > 0 {
		base = base[:idx]
	}

	return base
}

func _AllDigits(s string) bool {
	for _, r := range s {
		if r < '0' || r > '9' {
			return false
		}
	}

	return s != ""
}

func _LooksLikeStandardImport(importPath string) bool {
	first, _, _ := strings.Cut(importPath, "/")

	return !strings.Contains(first, ".")
}

func _ASTPackageFiles(pkgs map[string]*ast.Package) []*ast.File {
	if len(pkgs) == 0 {
		return nil
	}

	for name, pkg := range pkgs {
		if strings.HasSuffix(name, "_test") {
			continue
		}

		files := make([]*ast.File, 0, len(pkg.Files))
		for _, file := range pkg.Files {
			files = append(files, file)
		}

		return files
	}

	return nil
}

func _ASTPackageName(files []*ast.File) string {
	for _, file := range files {
		if file.Name != nil {
			return file.Name.Name
		}
	}

	return ""
}

func _ModuleImportDir(startDir string, importPath string) string {
	if startDir == "" || importPath == "" {
		return ""
	}

	dir := startDir
	for {
		goModPath := filepath.Join(dir, "go.mod")
		data, err := os.ReadFile(goModPath)
		if err == nil {
			return _ModuleImportDirFromGoMod(dir, string(data), importPath)
		}

		parent := filepath.Dir(dir)
		if parent == dir {
			return ""
		}

		dir = parent
	}
}

func _ModuleImportDirFromGoMod(moduleDir string, goMod string, importPath string) string {
	for _, line := range strings.Split(goMod, "\n") {
		fields := strings.Fields(line)
		if len(fields) < 2 || fields[0] != "module" {
			continue
		}

		modulePath := fields[1]
		if importPath != modulePath && !strings.HasPrefix(importPath, modulePath+"/") {
			return ""
		}

		rel := strings.TrimPrefix(importPath, modulePath)
		rel = strings.TrimPrefix(rel, "/")
		dir := filepath.Join(moduleDir, filepath.FromSlash(rel))
		if info, err := os.Stat(dir); err == nil && info.IsDir() {
			return dir
		}

		return ""
	}

	return ""
}

func _GoListImportDir(workDir string, importPath string, buildTags []string) string {
	if importPath == "" {
		return ""
	}

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	args := []string{"list", "-f", "{{.Dir}}"}
	if len(buildTags) > 0 {
		args = append(args, "-tags", strings.Join(buildTags, ","))
	}
	args = append(args, importPath)

	cmd := exec.CommandContext(ctx, "go", args...)
	if workDir != "" {
		cmd.Dir = workDir
	}

	out, err := cmd.Output()
	if err != nil {
		return ""
	}

	dir := strings.TrimSpace(string(out))
	if info, err := os.Stat(dir); err == nil && info.IsDir() {
		return dir
	}

	return ""
}

func (b *_ASTSchemaBuilder) _TypeParamEnv(typeSpec *ast.TypeSpec, args []_ASTSchemaArg, imports map[string]string) map[string]_ASTSchemaArg {
	if typeSpec == nil || typeSpec.TypeParams == nil || len(args) == 0 {
		return nil
	}

	env := map[string]_ASTSchemaArg{}
	argIndex := 0
	for _, field := range typeSpec.TypeParams.List {
		for _, name := range field.Names {
			if argIndex >= len(args) {
				return env
			}

			arg := args[argIndex]
			if arg._Imports == nil {
				arg._Imports = imports
			}
			env[name.Name] = arg
			argIndex++
		}
	}

	return env
}

func _SchemaArgs(args []ast.Expr, imports map[string]string) []_ASTSchemaArg {
	out := make([]_ASTSchemaArg, 0, len(args))
	for _, arg := range args {
		out = append(out, _ASTSchemaArg{_Expr: arg, _Imports: imports})
	}

	return out
}

func _ResolveSchemaArgs(args []ast.Expr, env map[string]_ASTSchemaArg, imports map[string]string) []_ASTSchemaArg {
	if len(args) == 0 {
		return nil
	}

	if len(env) == 0 {
		return _SchemaArgs(args, imports)
	}

	out := make([]_ASTSchemaArg, 0, len(args))
	for _, arg := range args {
		out = append(out, _ResolveSchemaArg(arg, env, imports))
	}

	return out
}

func _ResolveSchemaArg(expr ast.Expr, env map[string]_ASTSchemaArg, imports map[string]string) _ASTSchemaArg {
	switch t := expr.(type) {
	case *ast.Ident:
		mapped, ok := env[t.Name]
		if !ok || mapped._Expr == nil {
			return _ASTSchemaArg{_Expr: expr, _Imports: imports}
		}

		if mappedIdent, ok := mapped._Expr.(*ast.Ident); ok && mappedIdent.Name == t.Name {
			return _ASTSchemaArg{_Expr: expr, _Imports: imports}
		}

		return _ResolveSchemaArg(mapped._Expr, env, mapped._Imports)
	case *ast.StarExpr:
		inner := _ResolveSchemaArg(t.X, env, imports)

		return _ASTSchemaArg{_Expr: &ast.StarExpr{X: inner._Expr}, _Imports: inner._Imports}
	case *ast.ArrayType:
		inner := _ResolveSchemaArg(t.Elt, env, imports)

		return _ASTSchemaArg{_Expr: &ast.ArrayType{Elt: inner._Expr}, _Imports: inner._Imports}
	case *ast.MapType:
		key := _ResolveSchemaArg(t.Key, env, imports)
		value := _ResolveSchemaArg(t.Value, env, imports)

		return _ASTSchemaArg{
			_Expr: &ast.MapType{
				Key:   key._Expr,
				Value: value._Expr,
			},
			_Imports: value._Imports,
		}
	case *ast.IndexExpr:
		x := _ResolveSchemaArg(t.X, env, imports)
		index := _ResolveSchemaArg(t.Index, env, imports)

		return _ASTSchemaArg{
			_Expr: &ast.IndexExpr{
				X:     x._Expr,
				Index: index._Expr,
			},
			_Imports: index._Imports,
		}
	case *ast.IndexListExpr:
		indices := make([]ast.Expr, 0, len(t.Indices))
		argImports := imports
		for _, idx := range t.Indices {
			arg := _ResolveSchemaArg(idx, env, imports)
			indices = append(indices, arg._Expr)
			argImports = arg._Imports
		}

		x := _ResolveSchemaArg(t.X, env, imports)

		return _ASTSchemaArg{
			_Expr: &ast.IndexListExpr{
				X:       x._Expr,
				Indices: indices,
			},
			_Imports: argImports,
		}
	default:
		return _ASTSchemaArg{_Expr: expr, _Imports: imports}
	}
}

func _SchemaExprComponentSuffix(args []_ASTSchemaArg, imports map[string]string) string {
	parts := make([]string, 0, len(args))
	for _, arg := range args {
		argImports := arg._Imports
		if argImports == nil {
			argImports = imports
		}

		parts = append(parts, _SanitizeComponentName(_SchemaExprName(arg._Expr, argImports)))
	}

	return strings.Join(parts, ".")
}

func _SchemaExprName(expr ast.Expr, imports map[string]string) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		if pkg, ok := t.X.(*ast.Ident); ok {
			if importPath := imports[pkg.Name]; importPath != "" {
				return strings.ReplaceAll(importPath, "/", ".") + "." + t.Sel.Name
			}
		}

		return _SchemaExprName(t.X, imports) + "." + t.Sel.Name
	case *ast.StarExpr:
		return "ptr." + _SchemaExprName(t.X, imports)
	case *ast.ArrayType:
		return "array." + _SchemaExprName(t.Elt, imports)
	case *ast.IndexExpr:
		return _SchemaExprName(t.X, imports) + "." + _SchemaExprName(t.Index, imports)
	case *ast.IndexListExpr:
		parts := make([]string, 0, len(t.Indices)+1)
		parts = append(parts, _SchemaExprName(t.X, imports))
		for _, idx := range t.Indices {
			parts = append(parts, _SchemaExprName(idx, imports))
		}

		return strings.Join(parts, ".")
	default:
		return "type"
	}
}

func _SanitizeComponentName(name string) string {
	var b strings.Builder
	for _, r := range name {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9') || r == '.' || r == '_' || r == '-' {
			b.WriteRune(r)

			continue
		}

		b.WriteByte('_')
	}

	return b.String()
}

func (b *_ASTSchemaBuilder) _ComponentName(typeName string, typeSpec *ast.TypeSpec) string {
	if typeName == "" {
		return ""
	}

	if name := b._CustomComponentName(typeName, typeSpec); name != "" {
		return name
	}

	if b._PkgPath == "" {
		return typeName
	}

	name := shortPkgName(b._PkgPath) + "." + typeName
	if b._RootPkgPath != "" && b._PkgPath != b._RootPkgPath {
		return _FullOperationDocSchemaComponentName(name, b._PkgPath)
	}

	return name
}

func (b *_ASTSchemaBuilder) _CustomComponentName(typeName string, typeSpec *ast.TypeSpec) string {
	name := b._TypeSpecNames[typeSpec]
	if name == "" {
		return ""
	}

	if typeSpec == nil || typeSpec.Name == nil {
		return name
	}

	suffix := ""
	baseName := typeSpec.Name.Name
	if typeName != baseName && strings.HasPrefix(typeName, baseName+".") {
		suffix = strings.TrimPrefix(typeName, baseName)
	}

	return name + suffix
}

func (b *_ASTSchemaBuilder) _DisambiguatedComponentName(name string, typeName string) string {
	owner := b._PkgPath + "\x00" + typeName
	if existing, ok := b._ComponentOwners[name]; !ok || existing == owner {
		b._ComponentOwners[name] = owner

		return name
	}

	full := strings.ReplaceAll(b._PkgPath, "/", ".") + "." + typeName
	b._ComponentOwners[full] = owner

	return full
}

func _SchemaFromIdent(name string) *Schema {
	switch name {
	case "bool":
		return &Schema{Type: "boolean"}
	case "int", "int8", "int16", "int32", "uint", "uint8", "uint16", "uint32":
		return &Schema{Type: "integer", Format: "int32"}
	case "int64", "uint64":
		return &Schema{Type: "integer", Format: "int64"}
	case "float32":
		return &Schema{Type: "number", Format: "float"}
	case "float64":
		return &Schema{Type: "number", Format: "double"}
	case "string":
		return &Schema{Type: "string"}
	case "any":
		return &Schema{}
	default:
		return nil
	}
}

func _NullableSchema(schema *Schema) *Schema {
	if schema == nil {
		return nil
	}

	if schema.Ref != "" {
		return &Schema{
			Nullable: true,
			AllOf:    []*Schema{schema},
		}
	}

	copySchema := *schema
	copySchema.Nullable = true

	return &copySchema
}

func _IsByteExpr(expr ast.Expr) bool {
	ident, ok := expr.(*ast.Ident)
	if !ok {
		return false
	}

	return ident.Name == "byte" || ident.Name == "uint8"
}

